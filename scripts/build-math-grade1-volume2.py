def numeric(p,expr,h,e,unit='',ctx=''):
 assert re.fullmatch(r'[0-9+*/() -]+',expr)
 n=eval(expr,{'__builtins__':{}}); assert n==int(n) and 0<=n<=100
 n=int(n); wrong=[]
 for d in [1,-1,10,-10,2,3]:
  if 0<=n+d<=100 and n+d not in wrong: wrong.append(n+d)
  if len(wrong)==3:break
 return choice(p,f'{n}{unit}',[f'{v}{unit}' for v in wrong],h,e,ctx,dict(expression=expr,value=n,suffix=unit))
